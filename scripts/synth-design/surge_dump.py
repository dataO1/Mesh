"""Dump Surge XT parameter names, ranges and defaults per oscillator, filter,
waveshaper and effect type, straight from the synth (surgepy). Writes markdown.
Usage: surge_dump.py OUT.md
"""
import sys

import surgepy
from surgepy import constants as C


def names(prefix):
    return sorted((k, getattr(C, k)) for k in dir(C) if k.startswith(prefix) and isinstance(getattr(C, k), int))


def info(s, par):
    i = s.getParamInfo(par)
    return f"{s.getParamMin(par):g} .. {s.getParamMax(par):g} (default {s.getParamDef(par):g}) now `{s.getParamDisplay(par)}`" if i is None else str(i)


def row(s, par):
    return f"| {s.getParameterName(par.getId()) if hasattr(par, 'getId') else par} | {s.getParamMin(par):g} | {s.getParamMax(par):g} | {s.getParamDef(par):g} | {s.getParamDisplay(par)} |"


def settle(s):
    s.process()
    s.process()


def main():
    out = []
    s = surgepy.createSurge(48000)
    p = s.getPatch()
    sc = p["scene"][0]
    head = "| param | min | max | default | display |\n|---|---|---|---|---|"

    out.append("# Surge XT parameter reference (generated by scripts/synth-design/surge_dump.py)\n")
    out.append("Values are in the units `setParamVal` takes (display domain). Scene A shown; scene B mirrors it.\n")

    out.append("## Oscillator types\n")
    o = sc["osc"][0]
    for name, val in names("ot_"):
        s.setParamVal(o["type"], val)
        settle(s)
        out.append(f"### {name} = {val}\n\n{head}")
        out += [row(s, par) for par in o["p"]]
        out.append("")

    out.append("## Scene parameters\n")
    out.append(head)
    for k, v in sc.items():
        if k in ("osc", "filterunit", "wsunit", "adsr", "lfo"):
            continue
        if hasattr(v, "getId"):
            out.append(row(s, v))
    out.append("")

    out.append("## Filter types (fut_*)\n")
    out.append(", ".join(f"{n}={v}" for n, v in names("fut_")) + "\n")
    out.append(head)
    for k, v in sc["filterunit"][0].items():
        out.append(row(s, v))
    out.append("")
    out.append("## Waveshaper types (wst_*)\n")
    out.append(", ".join(f"{n}={v}" for n, v in names("wst_")) + "\n")
    out.append(head)
    for k, v in sc["wsunit"].items():
        out.append(row(s, v))
    out.append("")

    out.append("## Envelopes (adsr[0] = amp, adsr[1] = filter)\n")
    out.append(head)
    for k, v in sc["adsr"][0].items():
        out.append(row(s, v))
    out.append("")
    out.append("## LFOs (lfo[0..5] voice, lfo[6..11] scene)\n")
    out.append("Shapes: " + ", ".join(f"{n}={v}" for n, v in names("lt_")) + "\n")
    out.append(head)
    for k, v in sc["lfo"][0].items():
        out.append(row(s, v))
    out.append("")

    out.append("## Modulation sources (ms_*)\n")
    out.append(", ".join(f"{n}={v}" for n, v in names("ms_")) + "\n")
    out.append("## Scene modes, poly modes, filter configs\n")
    for pre in ("sm_", "pm_", "fb_", "fm_"):
        out.append(f"- `{pre}`: " + ", ".join(f"{n}={v}" for n, v in names(pre)))
    out.append("")

    out.append("## Effects (fxt_*)\n")
    fx = p["fx"][0]
    out.append(f"{len(p['fx'])} slots. Keys per slot: {list(fx.keys())}\n")
    for name, val in names("fxt_"):
        if val == 0:
            continue
        s.setParamVal(fx["type"], val)
        settle(s)
        out.append(f"### {name} = {val}\n\n{head}")
        out += [row(s, par) for par in fx["p"] if s.getParameterName(par.getId()).strip() and s.getParamMin(par) > -1e9]
        out.append("")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")


main()
